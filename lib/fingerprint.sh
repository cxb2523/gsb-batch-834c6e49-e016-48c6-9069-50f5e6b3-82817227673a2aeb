#!/bin/bash
# Content-fingerprint helpers for valve.zip.
#
# The zip's caching must follow its CONTENT, not its mtime: rebuilding valve.zip
# within the same second used to leave Last-Modified unchanged, so browsers kept
# their stale copy via 304. Both start.sh (zip build) and add-maps.sh (map
# injection) call update_valve_fingerprint after touching the zip; it hashes the
# actual bytes and rewrites:
#   proxy/valve-etag.conf      -> nginx `set $valve_etag "<sha256>";` (ETag)
#   proxy/valve-versions.json  -> {"valve.zip":"<sha256>"} (sw.js ?v= param)
# Sourced, not executed: `. ./lib/fingerprint.sh` then `update_valve_fingerprint`.

# Print the SHA-256 of a file with whatever the platform ships (GNU coreutils
# first, macOS/BSD perl fallback). Empty string on failure.
sha256_of() {
    local f="$1"
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$f" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$f" | awk '{print $1}'
    else
        perl -0777 -ne 'use Digest::SHA qw(sha256_hex); print sha256_hex($_)' "$f"
    fi
}

# Hash valve.zip (if present) and refresh both fingerprint files. Sets
# FINGERPRINT_CHANGED=1 when the hash differs from what nginx currently holds,
# so callers know the proxy container must be recreated to load the new ETag.
update_valve_fingerprint() {
    FINGERPRINT_CHANGED=0
    [ -f valve.zip ] || return 0

    local hash tmp_etag tmp_versions current
    hash=$(sha256_of valve.zip)
    [ -n "$hash" ] || { echo "  (warning: could not hash valve.zip — ETag left unchanged)"; return 0; }

    # Compare on the BARE hash (the file stores it wrapped in ETag quotes), so
    # an unchanged zip is a true no-op and repeat visits keep getting their 304.
    current=''
    if [ -f proxy/valve-etag.conf ]; then
      current=$(sed -n 's/.*set $valve_etag "\([0-9a-f]\{64\}\)".*/\1/p' proxy/valve-etag.conf)
    fi
    if [ "$hash" = "$current" ]; then
      return 0
    fi

    tmp_etag=$(mktemp)
    {
        echo '# Auto-generated by lib/fingerprint.sh — do not edit by hand.'
        echo '# SHA-256 of valve.zip bytes; nginx compares If-None-Match to this.'
        # RFC 7232 ETags are quoted strings; browsers echo the exact header back
        # in If-None-Match, so the variable holds the quoted hash and the nginx
        # `if ($http_if_none_match = $valve_etag)` equality test matches verbatim.
        # Backslash-escaping the quotes keeps printf from treating them as the
        # end of its format string; it emits one literal quote on each side.
        printf 'set $valve_etag \"%s\";\n' "$hash"
    } > "$tmp_etag"
    mv "$tmp_etag" proxy/valve-etag.conf

    tmp_versions=$(mktemp)
    printf '{\n  "valve.zip": "%s"\n}\n' "$hash" > "$tmp_versions"
    mv "$tmp_versions" proxy/valve-versions.json

    FINGERPRINT_CHANGED=1
    echo "  valve.zip content fingerprint updated ($hash)"
}
